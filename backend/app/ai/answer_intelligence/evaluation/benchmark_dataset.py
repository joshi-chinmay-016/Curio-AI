from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class BenchmarkCase(BaseModel):
    id: str
    category: str
    domain: str
    topic: str
    target_concept: str
    concept_definition: str
    expected_evidence: List[str]
    common_misconceptions: List[str]
    question: str
    learning_objective: str
    learner_answer: str
    expected_intent: str
    expected_relevance: str
    expected_correctness: str
    expected_completeness: str
    has_misconception: bool
    should_grant_mastery: bool
    should_deny_mastery: bool
    expected_evidence_items: List[str] = Field(default_factory=list)
    expected_missing_concepts: List[str] = Field(default_factory=list)

    def to_eval_dict(self) -> Dict[str, Any]:
        """Convert to the standard evaluation record dict consumed by BenchmarkRunner."""
        return {
            "id": self.id,
            "category": self.category,
            "domain": self.domain,
            "topic": self.topic,
            "target_concept": self.target_concept,
            "concept_definition": self.concept_definition,
            "expected_evidence": self.expected_evidence,
            "common_misconceptions": self.common_misconceptions,
            "question": self.question,
            "learning_objective": self.learning_objective,
            "learner_answer": self.learner_answer,
            "expected": {
                "intent": self.expected_intent,
                "relevance": self.expected_relevance,
                "correctness": self.expected_correctness,
                "completeness": self.expected_completeness,
                "has_misconception": self.has_misconception,
                "should_grant_mastery": self.should_grant_mastery,
                "should_deny_mastery": self.should_deny_mastery,
                "expected_evidence": self.expected_evidence_items,
                "missing_concepts": self.expected_missing_concepts,
            },
        }


